/// 把用户在扫描结果页勾选的条目变成一个可执行的清理目标。
/// 安全约束：只接受绝对路径（扫描产物本来就是绝对路径，这里再挡一道），
/// 每条命令都是 `rm -rf -- <path>` 的 argv 形式——不经 shell、不吃通配符；
/// 重复路径去重。
pub fn item_removal_target(items: &[ScanItem], needs_sudo: bool) -> Result<CleanupTarget, String> {
    if items.is_empty() {
        return Err("no items selected".to_string());
    }

    let mut seen = HashSet::new();
    let mut commands = Vec::new();
    for item in items {
        if !item.path.is_absolute() {
            return Err(format!(
                "refusing to remove relative path: {}",
                item.path.display()
            ));
        }
        if !seen.insert(item.path.clone()) {
            continue;
        }

        let path_text = item.path.to_string_lossy().to_string();
        let mut args: Vec<String> = Vec::new();
        let program;
        if needs_sudo {
            program = "sudo";
            args.push("rm".to_string());
        } else {
            program = "rm";
        }
        args.extend(["-rf", "--"].into_iter().map(String::from));
        args.push(path_text.clone());

        commands.push(CleanupCommand::new(
            // display 与 argv 一致：非 sudo 就是 `rm -rf --`，别把程序名重复一遍。
            if needs_sudo {
                format!("sudo rm -rf -- {}", path_display(&item.path))
            } else {
                format!("rm -rf -- {}", path_display(&item.path))
            },
            program,
            args,
            needs_sudo,
        ));
    }

    if commands.is_empty() {
        return Err("no items selected".to_string());
    }

    Ok(CleanupTarget {
        id: "selected-items",
        title: LocalizedText {
            zh_cn: "勾选的条目",
            en: "Selected items",
        },
        description: LocalizedText {
            zh_cn: "仅删除在扫描结果中勾选的条目，其余内容不动。",
            en: "Remove only the entries selected in the scan results; everything else stays.",
        },
        group: TargetGroup::User,
        risk: RiskLevel::Medium,
        requires_sudo: needs_sudo,
        threshold_summary: |_options: &CleanerOptions, language: Language| {
            i18n::tr(
                language,
                "逐项删除，无统一阈值",
                "Per-item removal; no shared threshold",
            )
            .to_string()
        },
        scan: scan_selected_items,
        dry_run_commands: Vec::new(),
        apply_commands: commands,
    })
}

